// Generates src/api/generated/{openapi.json,schema.d.ts} from the FastAPI app, or with
// --check verifies the committed files still match the backend (exit code 1 on drift).
// The schema is exported offline by backend/scripts/export_openapi.py — no server, no
// real database. The hand-written service types are checked against the generated
// schema at compile time by src/api/contract.check.ts.
//
// The exact output depends on the Python/FastAPI/Pydantic versions and on
// openapi-typescript (pinned in package.json). Those versions are recorded in the
// generated header, and --check reports a toolchain mismatch separately from API drift.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PYTHON = process.env.E2E_PYTHON ?? path.join(ROOT, '.venv', 'Scripts', 'python.exe')
const EXPORTER = path.join(ROOT, 'backend', 'scripts', 'export_openapi.py')
const OUT_DIR = path.join(ROOT, 'src', 'api', 'generated')
const TOOLCHAIN_PREFIX = '// Toolchain: '

const openapiTsVersion = createRequire(import.meta.url)('openapi-typescript/package.json').version
const pythonToolchain = execFileSync(PYTHON, [EXPORTER, '--toolchain'], { encoding: 'utf8' }).trim()
const toolchain = `${pythonToolchain}, openapi-typescript ${openapiTsVersion}`
const banner = `// Generated by \`npm run api:types\` from the FastAPI OpenAPI schema. Do not edit by hand.\n${TOOLCHAIN_PREFIX}${toolchain}\n`

const check = process.argv.includes('--check')
const workDir = check ? mkdtempSync(path.join(tmpdir(), 'api-types-')) : OUT_DIR
try {
  const schemaPath = path.join(workDir, 'openapi.json')
  execFileSync(PYTHON, [EXPORTER, schemaPath], { stdio: ['ignore', 'ignore', 'inherit'] })
  const schemaText = readFileSync(schemaPath, 'utf8')
  const typesText = banner + astToString(await openapiTS(JSON.parse(schemaText), { defaultNonNullable: false })).replace(/\r\n/g, '\n')

  if (!check) {
    writeFileSync(path.join(OUT_DIR, 'schema.d.ts'), typesText, 'utf8')
    console.log(`Wrote src/api/generated/openapi.json and src/api/generated/schema.d.ts (${toolchain})`)
  } else {
    const committedTypes = path.join(OUT_DIR, 'schema.d.ts')
    const recorded = existsSync(committedTypes)
      ? readFileSync(committedTypes, 'utf8').split(/\r?\n/).find((line) => line.startsWith(TOOLCHAIN_PREFIX))?.slice(TOOLCHAIN_PREFIX.length)
      : undefined
    if (recorded !== undefined && recorded !== toolchain) {
      console.error(`API types were generated with a different toolchain.\n  recorded: ${recorded}\n  current:  ${toolchain}\nAlign the versions (see CLAUDE.md), or regenerate with \`npm run api:types\` and review the diff before committing.`)
      process.exitCode = 1
    } else {
      const drift = [['openapi.json', schemaText], ['schema.d.ts', typesText]].filter(([name, fresh]) => {
        const committed = path.join(OUT_DIR, name)
        return !existsSync(committed) || readFileSync(committed, 'utf8').replace(/\r\n/g, '\n') !== fresh
      }).map(([name]) => name)
      if (drift.length > 0) {
        console.error(`API types are out of date with the backend: ${drift.join(', ')}. Run \`npm run api:types\`, then fix any errors \`tsc -b\` reports in src/api/contract.check.ts.`)
        process.exitCode = 1
      } else {
        console.log(`API types match the backend schema (${toolchain}).`)
      }
    }
  }
} finally {
  if (check) rmSync(workDir, { recursive: true, force: true })
}
